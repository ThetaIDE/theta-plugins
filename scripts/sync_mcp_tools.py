"""Copy the AI Assistant's tool layer into the Theta MCP Server plugin, so that plugin needs no other plugin.

The tools (what they read, what they change, how changes are previewed and approved) are written once, in
plugins/ai_assistant. The MCP server ships its own copy in plugins/theta_mcp/ide_tools, generated by this
script; edit the originals, never the copy. test_theta_mcp.py fails when the copy is out of date.

    python scripts/sync_mcp_tools.py           # write the copy
    python scripts/sync_mcp_tools.py --check   # exit 1 if it is out of date
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "plugins" / "ai_assistant"
TARGET = ROOT / "plugins" / "theta_mcp" / "ide_tools"
# source (relative to ai_assistant) -> name in ide_tools
MODULES = {
    "tools.py": "tools.py",
    "bridge.py": "bridge.py",
    "analysis.py": "analysis.py",
    "figures.py": "figures.py",
    "hub.py": "hub.py",
    "watch.py": "watch.py",
    "approval.py": "approval.py",
    "providers/chat_types.py": "chat_types.py",
}
REWRITES = [("from .providers.chat_types import", "from .chat_types import")]
INIT = '''"""ThetaIDE's tools, copied from the AI Assistant plugin so this plugin depends on no other.

Generated by scripts/sync_mcp_tools.py in theta-plugins: do not edit these files; edit plugins/ai_assistant and
run the script.
"""
'''


def header(source: str) -> str:
    return f"# Generated from plugins/ai_assistant/{source} by scripts/sync_mcp_tools.py. Do not edit.\n# ruff: noqa: I001\n"


def expected() -> dict[str, str]:
    files = {"__init__.py": INIT}
    for source, name in MODULES.items():
        text = (SOURCE / source).read_text(encoding="utf-8")
        for old, new in REWRITES:
            text = text.replace(old, new)
        files[name] = header(source) + text
    return files


def stale() -> list[str]:
    """The copied files that differ from what the script would write (or are missing, or extra)."""
    want = expected()
    out = [
        name
        for name, text in want.items()
        if not (TARGET / name).is_file() or (TARGET / name).read_text(encoding="utf-8") != text
    ]
    extra = [p.name for p in TARGET.glob("*.py") if p.name not in want] if TARGET.is_dir() else []
    return sorted(out + extra)


def write() -> None:
    TARGET.mkdir(exist_ok=True)
    for path in TARGET.glob("*.py"):
        path.unlink()
    for name, text in expected().items():
        (TARGET / name).write_text(text, encoding="utf-8")


if __name__ == "__main__":
    if "--check" in sys.argv:
        out_of_date = stale()
        if out_of_date:
            print("plugins/theta_mcp/ide_tools is out of date:", ", ".join(out_of_date))
            print("Run: python scripts/sync_mcp_tools.py")
            sys.exit(1)
        print("plugins/theta_mcp/ide_tools is up to date.")
    else:
        write()
        print(f"Wrote {len(expected())} files to {TARGET.relative_to(ROOT)}.")
