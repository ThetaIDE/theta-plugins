"""Theta MCP Server (Theta Hub plugin): ThetaIDE's tools for any agent that speaks MCP.

Start it, open a terminal in ThetaIDE and run Claude Code (or another MCP client) there: it can list and
diagnose runs, read configs, logs and metrics, plot curves, and, with your approval in the IDE, edit
configs, launch or stop runs and install Hub components.

It depends on no other plugin. Its tools (ide_tools/) are a copy of the AI Assistant's, generated by
scripts/sync_mcp_tools.py, so both offer the same tools under the same approval rules.

  server.py          the MCP server (HTTP on 127.0.0.1, a token per start; Qt-free)
  host.py            runs the tools on the right thread, with the user's approval for changes
  ide_tools/         the tools (generated: do not edit)
  project_config.py  environment variables for terminals, the workspace's .mcp.json, the fixed address
  harnesses.py       each agent's own config file (Claude Code, pi, opencode, Cursor, Codex, Antigravity)
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from frontend.plugins.base import Plugin, PluginManifest
from frontend.plugins.context import PluginContext

from . import harnesses, project_config
from .server import MCPServer

# Most MCP clients give up on a tool call after 60 s (pi's adapter and Codex by default), so one wait_for_runs
# call waits at most this long; its reply tells the agent to call again while runs are still going.
MAX_WAIT_SECONDS = 50


def capped_wait(minutes: Any) -> float:
    try:
        wanted = float(minutes) if minutes is not None else MAX_WAIT_SECONDS / 60
    except (TypeError, ValueError):
        wanted = MAX_WAIT_SECONDS / 60
    return max(0.0, min(wanted, MAX_WAIT_SECONDS / 60))


class ThetaMCPPlugin(Plugin):
    def __init__(self, manifest: PluginManifest):
        super().__init__(manifest)
        self.context: PluginContext | None = None
        self.server: MCPServer | None = None
        self.listeners: list = []  # settings pages that show the server's state
        self.home = Path.home()  # where agents keep their user-wide config (tests point it elsewhere)
        self.token_folder = project_config.user_config_dir()
        self.notes: list[str] = []  # what configuring the agents did, for the settings page
        self.host: Any = None  # the ToolHost; tests give a fake one

    def activate(self, context: PluginContext) -> None:
        self.context = context
        if self.host is None:
            self.host = self.make_host(context)
        context.register_command(
            command_id="theta_mcp.start",
            title="MCP: Start the ThetaIDE MCP server",
            callback=self.start,
            keywords=("mcp", "server", "claude", "codex", "agent", "tools", "start"),
            detail="Let Claude Code and other agents in the terminal use ThetaIDE's tools",
        )
        context.register_command(
            command_id="theta_mcp.stop",
            title="MCP: Stop the ThetaIDE MCP server",
            callback=self.stop,
            keywords=("mcp", "server", "stop"),
        )
        if context.get_setting("enabled", False):
            self.start()

    # ── The server ─────────────────────────────────────────────────────────

    def make_host(self, context: PluginContext) -> Any:
        from .host import ToolHost

        paths = getattr(context.window, "workspace_paths", None)
        data = Path(paths.data_dir) if paths is not None else Path(context.get_data_dir())
        return ToolHost(
            context.window,
            self.workspace(),
            data / "mcp" / "figures",  # the charts plot_metrics draws for agents
            status=lambda text: context.show_status_message(text, 6000),
        )

    def workspace(self) -> Path:
        """The project root, where agents look for .mcp.json. The window's WorkspacePaths is authoritative:
        PluginContext.get_workspace_dir() returns the run store's parent, the .thetaide folder in a real session."""
        paths = getattr(getattr(self.context, "window", None), "workspace_paths", None)
        return Path(paths.root) if paths is not None else Path(self.context.get_workspace_dir())

    def list_tools(self) -> list[dict[str, Any]]:
        return self.host.tool_definitions() if self.host is not None else []

    def call_tool(self, name: str, arguments: dict[str, Any], who: str) -> dict[str, Any]:
        if self.host is None:
            return {"text": "ThetaIDE's MCP server is shutting down.", "is_error": True, "images": []}
        if name == "wait_for_runs":
            arguments = {**arguments, "timeout_minutes": capped_wait(arguments.get("timeout_minutes"))}
        return self.host.call_tool(name, arguments, who)

    def start(self) -> bool:
        if self.context is None:
            return False
        if self.server is not None:
            self._announce(f"The MCP server is already running at {self.server.url}.")
            return True
        fixed = self.fixed_address()
        port = self.fixed_port() if fixed else int(self.context.get_setting("port", 0) or 0)
        token = project_config.fixed_token(self.token_folder) if fixed else None
        server = MCPServer(self.list_tools, self.call_tool, port=port, token=token)
        try:
            server.start()
        except OSError as exc:
            hint = f" Port {port} may be taken by another ThetaIDE window." if fixed else ""
            self._announce(f"The MCP server could not start: {exc}.{hint}")
            return False
        self.server = server
        project_config.export(server.url, server.token)
        self.configure_agents()
        self.context.set_setting("enabled", True)
        self._announce(f"MCP server running at {server.url}. Open a new terminal and start your agent there.")
        return True

    # ── Agents' config files ───────────────────────────────────────────────

    def fixed_address(self) -> bool:
        return bool(self.context is not None and self.context.get_setting("fixed_address", False))

    def fixed_port(self) -> int:
        port = self.context.get_setting("port", 0) if self.context is not None else 0
        return int(port or project_config.FIXED_PORT)

    def agent_ids(self) -> list[str]:
        ids = self.context.get_setting("agents", None) if self.context is not None else None
        return [i for i in ids if i in harnesses.BY_ID] if isinstance(ids, list) else list(harnesses.DEFAULT_IDS)

    def target(self) -> harnesses.Target:
        if self.server is not None and self.fixed_address():
            return harnesses.Target(self.server.url, self.server.token)
        return harnesses.Target(None, None)

    def configure_agents(self) -> list[str]:
        """Write every chosen agent's config. Agents that need the fixed address are skipped without it."""
        self.notes = harnesses.configure(self.agent_ids(), self.workspace(), self.home, self.target())
        for note in self.notes:
            if self.context is not None:
                self.context.log(note)
        return self.notes

    def set_agents(self, ids: list[str]) -> None:
        """Choose the agents to configure: newly chosen ones are written (while the server runs), dropped
        ones have the ThetaIDE entry removed from their files."""
        if self.context is None:
            return
        before = set(self.agent_ids())
        chosen = [i for i in ids if i in harnesses.BY_ID]
        self.context.set_setting("agents", chosen)
        dropped = [i for i in before if i not in chosen]
        self.notes = harnesses.unconfigure(dropped, self.workspace(), self.home)
        if self.server is not None:
            added = [i for i in chosen if i not in before]
            self.notes += harnesses.configure(added, self.workspace(), self.home, self.target())
        self._changed()

    def set_fixed_address(self, on: bool) -> None:
        """Keep the same address and token across restarts, or go back to new ones per start.
        A running server restarts so agents' files match it."""
        if self.context is None or on == self.fixed_address():
            return
        self.context.set_setting("fixed_address", bool(on))
        # Every entry moves: on, project entries give way to user-wide ones; off, the fixed token leaves every
        # user-wide file. The new entries are written when the server (re)starts.
        harnesses.unconfigure(self.agent_ids(), self.workspace(), self.home)
        if self.server is not None:
            self.stop(remember=False)
            self.start()
        else:
            self._changed()

    def renew_token(self) -> None:
        """Replace the fixed token (e.g. after it leaked). Agents' files are rewritten."""
        project_config.fixed_token(self.token_folder, renew=True)
        if self.server is not None and self.fixed_address():
            self.stop(remember=False)
            self.start()

    def stop(self, remember: bool = True) -> None:
        if self.server is not None:
            self.server.stop()
            self.server = None
            project_config.unexport()
            if self.context is not None:
                self._announce("MCP server stopped.")
        if remember and self.context is not None:
            self.context.set_setting("enabled", False)
        self._changed()

    def _announce(self, message: str) -> None:
        if self.context is not None:
            self.context.log(message)
            self.context.show_status_message(message, 8000)
        self._changed()

    def _changed(self) -> None:
        for listener in list(self.listeners):
            try:
                listener()
            except RuntimeError:  # its widget was deleted
                self.listeners.remove(listener)

    # ── Plugin lifecycle ───────────────────────────────────────────────────

    def can_deactivate(self) -> bool:
        return True

    def deactivate(self) -> None:
        self.stop(remember=False)  # disabling the plugin stops the server; it restarts if re-enabled
        if self.host is not None and hasattr(self.host, "close"):
            self.host.close()
        self.host = None
        self.listeners.clear()
        self.context = None

    def get_settings_widget(self, context: PluginContext):
        from .settings_widget import MCPSettings

        return MCPSettings(self)
